"""Hypothesis generation, inventory extraction, and candidate prioritization for authorization testing.

Processes scoped and redacted HAR entries to discover:
- Endpoints and parameters
- Object identifiers
- Dual-role authorization hypotheses (unauthorized read, unauthorized write, tenant-crossing)
- Compact Tev1 candidate prompts with strict deterministic fallback.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any
from urllib.parse import parse_qs, urlsplit

from bb.authz.model import (
    ApplicationModel,
    Endpoint,
    Hypothesis,
    Identity,
    ObjectRef,
    Parameter,
    Role,
    ScenarioSpec,
)
from bb.har import HarEntry
from bb.propose import find_id, propose
from bb.scope import Scope

# Common object identification patterns in URL paths or query params
ID_PATTERN = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$|^\d{1,10}$", re.IGNORECASE)

# State-changing action indicators in URL paths (e.g., /delete, /cancel, /transfer, /update, /logout, /approve)
STATE_CHANGING_PATH_ACTIONS = re.compile(
    r"/(delete|destroy|remove|cancel|transfer|mutate|update|edit|modify|logout|approve|revoke|reset|pay|checkout)(/|$|\?)",
    re.IGNORECASE,
)


def is_endpoint_state_changing(method: str, path: str) -> bool:
    """Fail-closed classification: method in POST/PUT/PATCH/DELETE OR action keyword in path."""
    m = method.upper()
    if m in ("POST", "PUT", "PATCH", "DELETE"):
        return True
    if STATE_CHANGING_PATH_ACTIONS.search(path):
        return True
    return False


def build_inventory_from_har(
    model: ApplicationModel,
    entries: list[HarEntry],
    scope: Scope,
) -> None:
    """Extract endpoints, parameters, and objects from scoped traffic entries."""
    for entry in entries:
        if not scope.is_in_scope(entry.url):
            continue

        parts = urlsplit(entry.url)
        path = parts.path
        host = parts.netloc.lower()
        method = entry.method.upper()

        # Parameter extraction: query
        query_params = parse_qs(parts.query)
        param_names: list[str] = []
        for qk, qvs in query_params.items():
            param_names.append(qk)
            val = qvs[0] if qvs else ""
            is_obj = bool(ID_PATTERN.match(val))
            model.add_parameter(Parameter(
                name=qk,
                kind="query",
                endpoint_key=f"{method} {path}",
                example_value=val,
                is_object_identifier=is_obj,
                provenance="observed",
            ))

        # Check path segments for object IDs
        path_segments = [s for s in path.split("/") if s]
        normalized_segments: list[str] = []
        for seg in path_segments:
            if ID_PATTERN.match(seg):
                normalized_segments.append("{id}")
                model.add_object(ObjectRef(
                    object_id=seg,
                    object_type="path_resource",
                    origin_url=entry.url,
                    provenance="observed",
                ))
            else:
                normalized_segments.append(seg)

        url_pattern = "/" + "/".join(normalized_segments)
        is_state_changing = is_endpoint_state_changing(method, path)

        model.add_endpoint(Endpoint(
            method=method,
            url_pattern=url_pattern,
            host=host,
            path=path,
            provenance="observed",
            is_state_changing=is_state_changing,
            auth_required=True,
            parameters=param_names,
        ))


def generate_hypotheses(
    model: ApplicationModel,
    har_path: str,
    scope: Scope,
    role_a: str = "A",
    role_b: str = "B",
    limit: int = 25,
) -> list[Hypothesis]:
    """Generate stateful authorization testing hypotheses using bb.propose and direct object patterns."""
    proposals_bundle = propose(har_path, scope=scope, program=model.program, limit=limit)
    out_dir = proposals_bundle.get("out")
    generated: list[Hypothesis] = []
    seen_fingerprints: set[str] = set()

    # 1. Load proposals generated by bb.propose from the output directory
    if out_dir and Path(out_dir).exists():
        scenario_files = list(Path(out_dir).glob("*.json"))
        for s_file in scenario_files:
            if s_file.name == "index.json":
                continue
            try:
                s_data = json.loads(s_file.read_text(encoding="utf-8"))
                claim = s_data.get("claim", {})
                c_type = claim.get("type", "idor_read")
                is_write = (c_type == "idor_write")
                s_name = s_data.get("name", s_file.stem)

                # Extract object id from steps
                obj_id = ""
                endpoint_url = ""
                for st in s_data.get("steps", []):
                    p = st.get("path", "")
                    if "/items/" in p:
                        obj_id = p.split("/items/")[-1].split("/")[0].split("?")[0]
                        endpoint_url = f"{s_data.get('base_url', '')}{p}"
                        break

                hypo_id = f"HYPO-{s_file.stem}"
                title = (
                    f"Broken object-level authorization (write/mutation): {role_b} mutates {role_a}'s resource {obj_id}"
                    if is_write else
                    f"Broken object-level authorization (read): {role_b} reads {role_a}'s resource {obj_id}"
                )
                description = f"Verify cross-account authorization boundary for object {obj_id} across {role_a} and {role_b}."

                spec = ScenarioSpec(
                    name=s_name,
                    base_url=s_data.get("base_url", ""),
                    steps=s_data.get("steps", []),
                    claim=claim,
                    cleanup=s_data.get("cleanup", []),
                    variables=s_data.get("variables", {}),
                    provenance="inferred",
                )

                hypo = Hypothesis(
                    id=hypo_id,
                    title=title,
                    description=description,
                    kind=c_type,
                    target_endpoint=endpoint_url or s_data.get("base_url", ""),
                    target_method="POST" if is_write else "GET",
                    object_id=obj_id,
                    owner_role=role_a,
                    attacker_role=role_b,
                    scenario=spec,
                    is_state_changing=is_write,
                    requires_approval=is_write,
                    priority_score=7 if is_write else 5,
                    provenance="inferred",
                    status="proposed",
                )
                if hypo.fingerprint not in seen_fingerprints:
                    seen_fingerprints.add(hypo.fingerprint)
                    model.add_hypothesis(hypo)
                    generated.append(hypo)
            except Exception:
                pass

    # 2. Direct model-derived hypotheses for observed endpoints with object IDs
    # (Ensures standalone GET /items/42 or parameterized endpoints generate valid hypotheses)
    for obj_id, obj_ref in model.objects.items():
        if len(generated) >= limit:
            break
        origin = urlsplit(obj_ref.origin_url)
        base_url = f"{origin.scheme}://{origin.netloc}"
        path = origin.path

        # Dual-role read hypothesis
        read_hypo_id = f"HYPO-READ-{obj_id}"
        read_scenario = {
            "name": f"authz-read-{obj_id}",
            "base_url": base_url,
            "steps": [
                {"id": "owner_read", "role": role_a, "method": "GET", "path": path},
                {"id": "attack_read", "role": role_b, "method": "GET", "path": path},
            ],
            "claim": {
                "type": "idor_read",
                "step": "attack_read",
                "owner_step": "owner_read",
                "owner": role_a,
                "attacker": role_b,
            },
        }

        read_spec = ScenarioSpec(
            name=read_scenario["name"],
            base_url=base_url,
            steps=read_scenario["steps"],
            claim=read_scenario["claim"],
            provenance="inferred",
        )

        read_is_write = is_endpoint_state_changing("GET", path)

        read_hypo = Hypothesis(
            id=read_hypo_id,
            title=f"Broken object-level authorization (read): {role_b} reads {role_a}'s resource {obj_id}",
            description=f"Attempt cross-account unauthorized read of object {obj_id} at {path}.",
            kind="idor_read",
            target_endpoint=f"{base_url}{path}",
            target_method="GET",
            object_id=obj_id,
            owner_role=role_a,
            attacker_role=role_b,
            scenario=read_spec,
            is_state_changing=read_is_write,
            requires_approval=read_is_write,
            priority_score=7 if read_is_write else 5,
            provenance="inferred",
            status="proposed",
        )

        if read_hypo.fingerprint not in seen_fingerprints:
            seen_fingerprints.add(read_hypo.fingerprint)
            model.add_hypothesis(read_hypo)
            generated.append(read_hypo)

    return generated


def build_compact_candidates_context(hypotheses: list[Hypothesis]) -> tuple[list[str], list[dict[str, Any]]]:
    """Build redacted, compact option summaries for Tev1 decision gateway.

    Returns:
        (option_ids, compact_summaries)
    """
    option_ids: list[str] = []
    summaries: list[dict[str, Any]] = []

    for h in hypotheses:
        option_ids.append(h.id)
        summaries.append({
            "id": h.id,
            "kind": h.kind,
            "method": h.target_method,
            "endpoint": h.target_endpoint,
            "is_write": h.is_state_changing,
            "owner": h.owner_role,
            "attacker": h.attacker_role,
        })

    # Always include safe defer option
    option_ids.append("defer")
    return option_ids, summaries


def prioritize_hypotheses_with_tev1(
    gateway: Any,  # DecisionGateway
    hypotheses: list[Hypothesis],
    context: dict[str, Any] | None = None,
) -> list[Hypothesis]:
    """Prioritize candidates using Tev1 structured choice or deterministic Python ordering."""
    if not hypotheses:
        return []

    option_ids, compact_summaries = build_compact_candidates_context(hypotheses)
    decision_context = {
        "task_type": "authorization_investigation_ranking",
        "candidates": compact_summaries,
    }
    if context:
        decision_context.update(context)

    # Convert candidates to synthetic swarm Tasks so existing gateway.select_task contract is honored
    from bb.swarm import Task
    candidate_tasks = [
        Task(
            kind=h.kind,
            target=h.target_endpoint,
            payload={"hypothesis_id": h.id, "is_write": h.is_state_changing, "object_id": h.object_id},
            priority=h.priority_score,
        )
        for h in hypotheses
    ]

    try:
        decision = gateway.select_task(candidate_tasks, context=decision_context)
    except Exception:
        # Gateway handles exceptions internally and provides deterministic fallback
        decision = {
            "selected_index": 0,
            "reason": "deterministic fallback on gateway exception",
            "confidence": 0.5,
            "provenance": {"fallback": True},
        }

    selected_idx = decision.get("selected_index", 0)
    selected_hypo_id = ""
    if 0 <= selected_idx < len(hypotheses):
        selected_hypo = hypotheses[selected_idx]
        selected_hypo_id = selected_hypo.id
        selected_hypo.decision_provenance = decision

    # Sort hypotheses: selected candidate first, then reads before writes unless high priority
    def sort_key(h: Hypothesis) -> tuple[int, int]:
        is_first = 0 if h.id == selected_hypo_id else 1
        return (is_first, -h.priority_score)

    sorted_hypotheses = sorted(hypotheses, key=sort_key)
    return sorted_hypotheses
